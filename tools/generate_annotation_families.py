"""Generate packaged annotation tables from one shared vocabulary (#225)."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'tools/annotation-families.json').read_text())
header = 'Generated by tools/generate_annotation_families.py; do not edit.'
outputs = {
    'src/xyang/encoding/annotation_families.py': '# ' + header + '\nFAMILIES = ' + repr(data) + '\n',
    'ts/src/encoding/annotation-families.ts': '// ' + header + '\nexport const ANNOTATION_FAMILIES = ' + json.dumps(data, indent=2) + ' as const;\n',
    'zig/src/encoding/annotation_families.zig': '// ' + header + '\npub const Family = struct { prefix: u8, pattern: []const u8 };\n' + ''.join(
        f'pub const {name}: Family = .{{ .prefix = \'{value["prefix"]}\', .pattern = {json.dumps(value["pattern"])} }};\n'
        for name, value in data.items()),
}
for path, content in outputs.items():
    target = ROOT / path
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f'{path} is stale; run python tools/generate_annotation_families.py')
    else:
        target.write_text(content)
