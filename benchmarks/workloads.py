"""Checked-in benchmark workloads shared by the Python and TypeScript workers.

Both workers receive the same resolved spec (file paths, include paths, the
instance file) from ``release_bench.py``, so they parse and validate identical
inputs. The large instance is generated deterministically and checked against a
pinned SHA-256; a mismatch is an error, never a silent change of workload.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

ROOT = Path(__file__).resolve().parent.parent
WORKLOAD_DIR = Path(__file__).resolve().parent / "workloads"

INVENTORY_INTERFACES = 10_000
INVENTORY_LAGS = 16
INVENTORY_SHA256 = "bfd8473371c798702ca9e586e439fb3fefcfc73ec3255784142e837ab88913a1"


def inventory_instance(interfaces: int = INVENTORY_INTERFACES, lags: int = INVENTORY_LAGS) -> dict[str, Any]:
    """RFC 7951 instance of ``interface-inventory.yang`` (no randomness)."""
    duplex = ("full", "half", "auto")
    rows = []
    for i in range(interfaces):
        row: dict[str, Any] = {
            "name": f"eth{i}",
            "description": f"uplink port {i} rack {i // 48}",
            "enabled": i % 7 != 0,
            "mtu": 1500 if i % 5 else 9000,
            "speed": str(1_000_000 * (1 + i % 4)),
            "duplex": duplex[i % 3],
            "tags": [f"rack{i // 48}", "prod" if i % 2 else "lab"],
            "counters": {"in-octets": str(i * 7919), "out-octets": str(i * 104729)},
        }
        if i % 4 == 0:
            row["lag"] = f"bond{i % lags}"
        rows.append(row)
    lag_rows = [{"name": f"bond{j}", "min-links": 1 + j % 8} for j in range(lags)]
    return {"interface-inventory:inventory": {"interface": rows, "lag": lag_rows}}


def _render_inventory() -> bytes:
    return (json.dumps(inventory_instance(), separators=(",", ":"), sort_keys=True) + "\n").encode("utf-8")


@dataclass(frozen=True)
class Workload:
    name: str
    title: str
    parse_modules: tuple[str, ...]
    validate_module: str
    instance: str
    instance_note: str
    generator: Callable[[], bytes] | None = None
    expected_sha256: str | None = None
    list_entries: int | None = None
    extra: dict[str, Any] = field(default_factory=dict)


