class WorkloadError(RuntimeError):
    pass


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _yang_size(paths: list[Path]) -> dict[str, int]:
    lines = sum(len(p.read_text(encoding="utf-8").splitlines()) for p in paths)
    return {"files": len(paths), "lines": lines, "bytes": sum(p.stat().st_size for p in paths)}


def materialize(workload: Workload, out_dir: Path) -> dict[str, Any]:
    """Resolve absolute paths (writing a generated instance into ``out_dir``) and describe sizes."""
    if workload.generator is not None:
        data = workload.generator()
        digest = _sha256(data)
        if digest != workload.expected_sha256:
            raise WorkloadError(
                f"workload {workload.name!r}: generated instance SHA-256 {digest} != pinned "
                f"{workload.expected_sha256}; update INVENTORY_SHA256 deliberately if the workload changed"
            )
        out_dir.mkdir(parents=True, exist_ok=True)
        instance = out_dir / workload.instance
        instance.write_bytes(data)
    else:
        instance = ROOT / workload.instance
        data = instance.read_bytes()
        digest = _sha256(data)

    parse_paths = [ROOT / p for p in workload.parse_modules]
    validate_path = ROOT / workload.validate_module
    for path in [*parse_paths, validate_path]:
        if not path.is_file():
            raise WorkloadError(f"workload {workload.name!r}: missing {path}")

    def module_spec(path: Path) -> dict[str, Any]:
        return {"path": str(path), "include": [str(path.parent)]}

    return {
        "spec": {
            "parse": [module_spec(p) for p in parse_paths],
            "validate": {"module": module_spec(validate_path), "instance": str(instance)},
        },
        "description": {
            "name": workload.name,
            "title": workload.title,
            "parse_modules": list(workload.parse_modules),
            "parse_size": _yang_size(parse_paths),
            "validate_module": workload.validate_module,
            "instance": workload.instance,
            "instance_note": workload.instance_note,
            "instance_bytes": len(data),
            "instance_sha256": digest,
            "list_entries": workload.list_entries,
        },
    }
